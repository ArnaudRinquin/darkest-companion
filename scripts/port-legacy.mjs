// One-off: converts the v1 data snapshot (test/fixtures/legacy.json, dumped from
// the old src/data/*.js) into src/data/curios.generated.ts. Kept so the port is
// reproducible; hand edits go in src/data/curios.ts overrides, not here.
import { readFileSync, writeFileSync } from 'node:fs';

const legacy = JSON.parse(readFileSync(new URL('../test/fixtures/legacy.json', import.meta.url)));
const ACTIVATORS = {
  Nothing: 'nothing', Antivenom: 'antivenom', Bandage: 'bandage', 'Dog Treats': 'dogTreats',
  'Holy Water': 'holyWater', 'Medicinal Herb': 'medicinalHerb', Shovel: 'shovel',
  'Skeleton Key': 'skeletonKey', Torch: 'torch',
};
const SHARED = 9; // first 9 entries of every region list are the shared curios
const slug = (s) => s.toLowerCase().replace(/['’]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const convert = (c, region) => ({
  id: `${region === 'shared' ? '' : region + '-'}${slug(c.name)}`,
  name: c.name,
  region,
  ...(c.icon && { icon: c.icon.replace('./icons/', '') }),
  ...(c.description && { description: c.description }),
  options: c.options.map((o) => ({
    activator: ACTIVATORS[o.activator.label] ?? (() => { throw new Error(o.activator.label); })(),
    outcomes: o.outcomes.map((x) => ({
      chance: x.chances,
      label: x.type.label,
      ...(x.amount != null && { amount: x.amount }),
    })),
  })),
});

const curios = [
  ...legacy.curios.ruins.slice(0, SHARED).map((c) => convert(c, 'shared')),
  ...Object.entries(legacy.curios).flatMap(([region, list]) => list.slice(SHARED).map((c) => convert(c, region))),
];

writeFileSync(
  new URL('../src/data/curios.generated.ts', import.meta.url),
  `// Generated by scripts/port-legacy.mjs from the v1 data. Do not edit by hand.\nimport type { Curio } from './types';\n\nexport const legacyCurios: Curio[] = ${JSON.stringify(curios, null, 2)};\n`,
);
console.log(`${curios.length} curios`);
